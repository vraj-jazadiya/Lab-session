public abstract class tableCreationUsingArray {
    public static void main(String[] args) {

        int n = 5;

        System.out.println("Multiplication Table of " + n + " is:");
        for (int i = 1; i <= 10; i++) {
            System.err.println(n + " x " + i + " = " + (n * i));
        }
    }
}
